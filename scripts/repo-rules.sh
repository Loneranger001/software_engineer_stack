#!/bin/sh
# repo-rules.sh — list a repo's own rules files (the coding standards and
# agent instructions its team wrote), so every stage follows the same set.
#
# Usage: repo-rules.sh <repo> [file ...]
#   repo   the repository root (or any path inside it)
#   file   files being changed/reviewed: adds the nested AGENTS.md found in
#          their directories and ancestors, nearest last
#
# A root AGENTS.md is the manifest: the rules are AGENTS.md plus the repo-local
# Markdown files it links to (one level, e.g. CODING_STANDARDS.md,
# NAMING_CONVENTIONS.md), and the same for each nested AGENTS.md. Nothing else
# is picked up by name. Only a repo with no root AGENTS.md falls back to
# scanning for conventional names (CODING_STANDARDS.md, CONTRIBUTING.md,
# Copilot instructions, ...) and nested AGENTS.md / CLAUDE.md.
#
# Output — the root set first, then each nested set, nearest the file last
# (a nearer set wins; two files of one set that disagree are a question):
#   rules:   <repo-relative path>         one per file found
#   missing: <link> (linked from <file>)  a linked .md that is not a file in the repo
#   tooling: <repo-relative path>         lint/test/format configs to run, not read
#   or "rules: (none found ...)" — then framework standards/ apply.
# Files generated by build_copilot.py in framework versions up to 0.6 (an adapter
# installed into a work repo)
# are skipped: they are the framework's instructions, not the repo's rules.
set -eu

[ $# -ge 1 ] || { echo "usage: repo-rules.sh <repo> [file ...]" >&2; exit 2; }
case "$1" in -h|--help) sed -n '2,25p' "$0"; exit 0 ;; esac
[ -e "$1" ] || { echo "error: no such path: $1" >&2; exit 2; }
START=$1; [ -d "$START" ] || START=$(dirname "$START")
ROOT=$(git -C "$START" rev-parse --show-toplevel 2>/dev/null) \
  || { echo "error: $1 is not inside a git repository" >&2; exit 2; }
PROOT=$(cd "$ROOT" && pwd -P)   # physical root, to compare resolved link targets
shift

MARKER="generated by software-engineer-stack scripts/build_copilot.py"
NL='
'
SEEN=""

skip() {  # skip <absolute path> — true for a non-file, a generated file, or one already listed
  [ -n "$1" ] && [ -f "$1" ] || return 0
  grep -q "$MARKER" "$1" 2>/dev/null && return 0
  case "$NL$SEEN$NL" in *"$NL${1#"$ROOT"/}$NL"*) return 0 ;; esac
  return 1
}

emit() {  # emit <kind> <absolute path> — once per file, skipping generated ones
  skip "$2" && return 0
  rel=${2#"$ROOT"/}
  SEEN="$SEEN$NL$rel"
  printf '%-8s %s\n' "$1:" "$rel"
}

# case-insensitive name match within one directory, sorted for stable output
find_names() {  # find_names <dir> <name>...
  d=$1; shift
  [ -d "$d" ] || return 0
  for n in "$@"; do
    find "$d" -maxdepth 1 -type f -iname "$n" 2>/dev/null
  done | LC_ALL=C sort -u
}

# emit_all <kind> — emit every path read from stdin, one per line. Callers
# feed it with a here-doc, which runs in this shell (so SEEN persists) and
# keeps paths with spaces intact.
emit_all() {
  while IFS= read -r f; do emit "$1" "$f"; done
}

# links <file> — the targets of its Markdown links, inline and reference-style,
# one per line: <angle brackets>, titles, %20 and #anchors removed
links() {
  { grep -o '\]([^)]*)' "$1" | sed 's/^](//; s/)$//'
    sed -n 's/^ \{0,3\}\[[^]]*\]:[[:space:]]*//p' "$1"
  } 2>/dev/null | sed -e 's/^<\([^>]*\)>.*/\1/' -e 't done' -e 's/[[:space:]].*$//' \
                      -e ':done' -e 's/%20/ /g' -e 's/#.*$//'
}

# emit_set <AGENTS.md> — the file, then every .md it links to that is a file
# inside the repo; any other .md link is reported as missing
emit_set() {
  skip "$1" && return 0
  emit rules "$1"
  _src=$1
  while IFS= read -r _t; do
    case "$_t" in ''|*://*|mailto:*) continue ;; esac
    case "$_t" in *.[mM][dD]) ;; *) continue ;; esac
    case "$_t" in /*) _p="$ROOT$_t" ;; *) _p="$(dirname "$_src")/$_t" ;; esac
    _f=$(cd "$(dirname "$_p")" 2>/dev/null && printf '%s/%s' "$(pwd -P)" "$(basename "$_p")") || _f=""
    case "$_f" in
      "$PROOT"/*) if [ -f "$_f" ]; then emit rules "$ROOT/${_f#"$PROOT"/}"; continue; fi ;;
    esac
    printf '%-8s %s (linked from %s)\n' "missing:" "$_t" "${_src#"$ROOT"/}"
  done <<LIST
$(links "$_src")
LIST
}

RULE_NAMES="AGENTS.md AGENT.md CLAUDE.md CODING_STANDARDS.md CODING-STANDARDS.md
CODINGSTANDARDS.md STANDARDS.md STYLEGUIDE.md STYLE_GUIDE.md STYLE-GUIDE.md
CONVENTIONS.md NAMING_CONVENTIONS.md NAMING-CONVENTIONS.md CONTRIBUTING.md"

# 1. repo-wide rules: the root AGENTS.md and what it links to; without one,
#    conventional names at the root, then docs/, then .github/
AGENTS=$(find_names "$ROOT" AGENTS.md | head -n 1)
if [ -n "$AGENTS" ] && ! skip "$AGENTS"; then
  MANIFEST=1
  emit_set "$AGENTS"
else
  MANIFEST=""
  # shellcheck disable=SC2086
  emit_all rules <<LIST
$(find_names "$ROOT" $RULE_NAMES)
$(find_names "$ROOT/docs" $RULE_NAMES)
$(find_names "$ROOT/.github" CONTRIBUTING.md copilot-instructions.md)
$(if [ -d "$ROOT/.github/instructions" ]; then
    find "$ROOT/.github/instructions" -maxdepth 1 -type f -name '*.instructions.md' | LC_ALL=C sort
  fi)
LIST
fi

# 2. nested rules above each changed file, outermost first
for target in "$@"; do
  case "$target" in /*) abs=$target ;; *) abs="$ROOT/$target" ;; esac
  d=$abs; [ -d "$d" ] || d=$(dirname "$d")
  chain=""
  while [ "${d#"$ROOT"/}" != "$d" ]; do   # strictly below ROOT
    chain="$d$NL$chain"
    d=$(dirname "$d")
  done
  while IFS= read -r dir; do
    [ -n "$dir" ] || continue
    if [ -n "$MANIFEST" ]; then
      while IFS= read -r nested; do
        emit_set "$nested"
      done <<LIST
$(find_names "$dir" AGENTS.md)
LIST
    else
      emit_all rules <<LIST
$(find_names "$dir" AGENTS.md CLAUDE.md)
LIST
    fi
  done <<LIST
$chain
LIST
done

[ -n "$SEEN" ] || echo "rules:   (none found — use framework standards/, and the surrounding code's style where they are silent)"

# 3. tooling configs: run these tools (verify-code), don't read them as prose
emit_all tooling <<LIST
$(find_names "$ROOT" .editorconfig pyproject.toml setup.cfg tox.ini ruff.toml .ruff.toml \
   .flake8 mypy.ini .mypy.ini pytest.ini .pylintrc .shellcheckrc .pre-commit-config.yaml \
   .sqlfluff Makefile)
LIST
exit 0
