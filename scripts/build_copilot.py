#!/usr/bin/env python3
"""Generate the GitHub Copilot adapter from the canonical skills.

Produces, in the target repo:
    .github/skills/<name>/SKILL.md       one per skills/*/SKILL.md (model-invoked or /name)
    .github/agents/<name>.agent.md       one per agents/*.md (Copilot custom agents)
    .github/copilot-instructions.md      framework overview + shared rules
and, in the stack repo itself:
    AGENTS.md                            universal entry point (AGENTS.md-aware tools)
    copilot/                             self-contained Copilot-native plugin
                                         (plugin.json + skills/ + agents/*.agent.md
                                         + bundled templates/checklists/core/standards)

Canonical content lives in skills/; regenerate after editing them. Generated
files carry a marker line and are only overwritten when the marker is present,
so hand-created files are never clobbered. The one exception to "generated
output is disposable" is knowledge/: /retro appends lessons and decisions to
the per-install copy, so those entries are merged back on top of the canonical
content instead of being replaced (see merge_knowledge_file).

Usage:
    build_copilot.py [--target /path/to/work-repo] [--stack-root /path/to/this-repo]
                     [--self-contained]
    build_copilot.py --check     regenerate into a scratch copy and fail (exit 1) if the
                                 committed output in this repo differs — run by CI
                                 and the pre-commit hook

Prompt files (.github/prompts/) are no longer generated: skills are slash
commands in VS Code chat, and prompt files are deprecated in the Copilot
harness. Rebuilding removes the ones earlier versions generated.

Default target is the stack repo. When targeting a work repo, path references
in skills point back at the stack root by absolute path — unless
--self-contained is given, which bundles the framework data (templates,
checklists, core, standards, scripts, knowledge) into <target>/.github/se-stack/
and points all references there, so the work repo needs no framework checkout.
"""
import argparse
import filecmp
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import NamedTuple

MARKER = "generated by software-engineer-stack scripts/build_copilot.py; do not edit by hand"

# scripts the skills call at run time — shipped with every install. build/check
# tooling (build_copilot.py, check_knowledge.py) stays in the framework repo.
RUNTIME_SCRIPTS = ("*.sh", "status.py", "handoff.py", "checkpoint.py", "xsearch.py")

# generated output inside the stack repo, compared by --check (.github/prompts is
# retired output: listed so a leftover generated prompt file fails the check)
GENERATED_PATHS = ("AGENTS.md", ".github/copilot-instructions.md", ".github/prompts",
                   ".github/skills", ".github/agents", "copilot")
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store")


def yaml_str(value: str) -> str:
    """A frontmatter scalar that stays valid YAML ("Use when: x" unquoted is a parse error)."""
    if re.search(r":(\s|$)|\s#|^[\[\]{}>|*&!%@`'\"#,?-]|^\s|\s$", value):
        return json.dumps(value, ensure_ascii=False)
    return value


def runtime_scripts(stack: Path) -> list[Path]:
    return sorted({p for pat in RUNTIME_SCRIPTS for p in (stack / "scripts").glob(pat)})


class Refs(NamedTuple):
    """Where ${CLAUDE_PLUGIN_ROOT} paths land in one output layout. The plugin and
    the self-contained bundle ship the reviewers only as <name>.agent.md, and the
    bundle keeps skills under .github/skills/ rather than next to the data."""
    root: str
    agents: str
    skills: str
    agent_ext: str = ".md"

    @classmethod
    def at(cls, root: str) -> "Refs":
        return cls(root, f"{root}/agents", f"{root}/skills")


PLUGIN_REFS = Refs("<plugin-root>", "<plugin-root>/agents", "<plugin-root>/skills", ".agent.md")
BUNDLE_REFS = Refs(".github/se-stack", ".github/agents", ".github/skills", ".agent.md")


def substitute(text: str, refs: Refs) -> str:
    text = re.sub(r"\$\{CLAUDE_PLUGIN_ROOT\}/agents/([\w-]+)\.md\b",
                  lambda m: f"{refs.agents}/{m.group(1)}{refs.agent_ext}", text)
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/agents/", refs.agents + "/")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/skills/", refs.skills + "/")
    return text.replace("${CLAUDE_PLUGIN_ROOT}", refs.root)


# Claude Code tool names -> Copilot custom-agent tool aliases; without a tools
# line a Copilot custom agent gets every tool, edit included
COPILOT_TOOLS = {"Read": "read", "NotebookRead": "read", "Grep": "search", "Glob": "search",
                 "Bash": "execute", "Edit": "edit", "MultiEdit": "edit", "Write": "edit",
                 "NotebookEdit": "edit", "WebFetch": "web", "WebSearch": "web",
                 "Task": "agent", "TodoWrite": "todo"}

# optional SKILL.md frontmatter passed through to Copilot skills (VS Code reads all three)
SKILL_FIELDS = ("argument-hint", "user-invocable", "disable-model-invocation")


def skill_frontmatter(fm: dict) -> str:
    extra = "".join(f"{k}: {yaml_str(fm[k])}\n" for k in SKILL_FIELDS if fm.get(k))
    return f"---\nname: {fm['name']}\ndescription: {yaml_str(fm['description'])}\n{extra}---\n"


def agent_frontmatter(fm: dict) -> str:
    tools = ""
    if fm.get("tools"):
        names = [COPILOT_TOOLS.get(t.strip(), t.strip()) for t in fm["tools"].split(",") if t.strip()]
        tools = f"tools: {json.dumps(list(dict.fromkeys(names)))}\n"
    return f"---\nname: {fm['name']}\ndescription: {yaml_str(fm['description'])}\n{tools}---\n"


def copy_skill_support(src_dir: Path, dest_dir: Path, refs: Refs) -> None:
    """Copy a skill's non-SKILL.md files (assets/, reference .md files, ...) next to its
    generated SKILL.md. Markdown files get the same ${CLAUDE_PLUGIN_ROOT} substitution as
    SKILL.md, so a reference file a skill loads on demand points at the right paths."""
    for f in sorted(src_dir.rglob("*")):
        rel = f.relative_to(src_dir)
        if not f.is_file() or rel == Path("SKILL.md") or "__pycache__" in rel.parts or f.suffix == ".pyc":
            continue
        dest = dest_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if f.suffix == ".md":
            dest.write_text(substitute(f.read_text(), refs))
        else:
            shutil.copy2(f, dest)

PLUGIN_NOTE = (
    "> Path note: `<plugin-root>` is the directory containing this plugin's\n"
    "> `plugin.json` (the plugin install root): two levels above a skill's\n"
    "> SKILL.md, one above an agent's `agents/` folder. All framework files\n"
    "> referenced below live inside it; pass it resolved to any agent you launch.\n"
)


def strip_path_note(body: str) -> str:
    # remove the canonical skills' path-note blockquote (paths are pre-substituted
    # in generated output, so the note would be stale there)
    return re.sub(r"^> Path note:.*\n(?:^>.*\n)*\n?", "", body, count=1, flags=re.M)


def parse_frontmatter(text: str, path: Path) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        sys.exit(f"error: {path}: no frontmatter block")
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"').strip("'")
    if "name" not in fm or "description" not in fm:
        sys.exit(f"error: {path}: frontmatter missing name/description")
    return fm, m.group(2)


def write_generated(path: Path, content: str) -> None:
    if path.exists() and MARKER not in path.read_text():
        sys.exit(f"error: {path} exists and was not generated by this script — refusing to overwrite")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"wrote {path}")


def split_blocks(text: str) -> list[tuple[bool, str]]:
    """Split markdown into (is_bullet, chunk) pieces.

    A bullet block starts at a top-level "- " line and absorbs the indented or
    blank lines that follow, so multi-line entries stay intact. Everything else
    (headings, blockquotes, marker comments) accumulates as non-bullet chunks.
    """
    pieces: list[tuple[bool, str]] = []
    cur: list[str] = []
    in_bullet = False
    for line in text.splitlines(keepends=True):
        if line.startswith("- "):
            if cur:
                pieces.append((in_bullet, "".join(cur)))
            cur, in_bullet = [line], True
        elif in_bullet and (not line.strip() or line[:1] in " \t"):
            cur.append(line)
        else:
            if in_bullet:
                pieces.append((True, "".join(cur)))
                cur, in_bullet = [], False
            cur.append(line)
    if cur:
        pieces.append((in_bullet, "".join(cur)))
    return pieces


def merge_knowledge_file(canonical: str, existing: str) -> str:
    """Canonical content plus any entries only the install copy has.

    knowledge/ files are append-only logs: /retro adds bullet entries to the
    per-install copy. Rebuilding must not lose them, so local-only bullets are
    re-appended after the canonical content. Comparison ignores whitespace so a
    reflowed entry is not duplicated.

    Append-only means deletion does not propagate: an entry pruned from the
    canonical file by a /retro curation pass looks identical to a locally-added
    one and is preserved. To push a pruning through to an install copy, delete
    that copy's knowledge/ file (or the whole generated directory) and rebuild.
    """
    norm = lambda b: " ".join(b.split())
    known = {norm(b) for is_bullet, b in split_blocks(canonical) if is_bullet}
    extra = [b for is_bullet, b in split_blocks(existing) if is_bullet and norm(b) not in known]
    if not extra:
        return canonical
    out = canonical if canonical.endswith("\n") else canonical + "\n"
    return out + "".join(b if b.endswith("\n") else b + "\n" for b in extra)


def stash_knowledge(out: Path) -> dict[str, str]:
    """Read the install copy's knowledge/ before the output tree is rebuilt."""
    kdir = out / "knowledge"
    if not kdir.is_dir():
        return {}
    return {str(p.relative_to(kdir)): p.read_text()
            for p in sorted(kdir.rglob("*")) if p.is_file()}


def restore_knowledge(out: Path, stashed: dict[str, str]) -> None:
    """Merge stashed entries back into the freshly copied knowledge/."""
    kdir = out / "knowledge"
    for rel, existing in sorted(stashed.items()):
        dest = kdir / rel
        if dest.exists():
            canonical = dest.read_text()
            merged = merge_knowledge_file(canonical, existing)
            if merged != canonical:
                dest.write_text(merged)
                print(f"  merged local entries into knowledge/{rel}")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(existing)
            print(f"  kept local-only knowledge/{rel}")


def prune_generated(gh: Path, skill_names: list[str], agent_names: list[str]) -> None:
    """Delete generated skills/agents whose canonical source was removed, and every
    generated prompt file (no longer an output).

    Only files carrying the generator marker are touched, so hand-created
    prompts, skills, and agents in a work repo's .github/ are never deleted.
    """
    def is_generated(f: Path) -> bool:
        return f.is_file() and MARKER in f.read_text(errors="ignore")

    for f in sorted((gh / "prompts").glob("*.prompt.md")):
        if is_generated(f):
            f.unlink()
            print(f"removed {f}")
    if (gh / "prompts").is_dir() and not any((gh / "prompts").iterdir()):
        (gh / "prompts").rmdir()
    for d in sorted(p for p in (gh / "skills").glob("*") if p.is_dir()):
        if d.name not in skill_names and is_generated(d / "SKILL.md"):
            shutil.rmtree(d)
            print(f"removed {d}/")
    for f in sorted((gh / "agents").glob("*.agent.md")):
        if f.name[:-len(".agent.md")] not in agent_names and is_generated(f):
            f.unlink()
            print(f"removed {f}")


def build_skill(fm: dict, body: str, refs: Refs) -> str:
    body = substitute(strip_path_note(body), refs)
    return f"{skill_frontmatter(fm)}<!-- {MARKER} -->\n{body}"


def build_agent(fm: dict, body: str, refs: Refs) -> str:
    body = substitute(strip_path_note(body), refs)
    return f"""{agent_frontmatter(fm)}<!-- {MARKER} -->
> Part of **software-engineer-stack** ({refs.root}). You are read-only: report
> findings in your defined format; never modify files or repository state.

{body}"""


def build_plugin(stack: Path, skill_dirs: list[Path], agent_files: list[Path]) -> None:
    """Write the committed, self-contained Copilot-native plugin at <stack>/copilot/."""
    out = stack / "copilot"
    gen_marker = out / ".generated"
    if out.exists() and not gen_marker.exists():
        sys.exit(f"error: {out} exists and was not generated by this script — refusing to overwrite")
    stashed = stash_knowledge(out)
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir()
    gen_marker.write_text(MARKER + "\n")

    src_manifest = json.loads((stack / ".claude-plugin" / "plugin.json").read_text())
    manifest = {
        "name": src_manifest["name"],
        "version": src_manifest.get("version", "0.0.0"),
        "description": src_manifest.get("description", ""),
        "author": src_manifest.get("author", {}),
        "license": src_manifest.get("license", "MIT"),
        "keywords": src_manifest.get("keywords", []),
    }
    # NOTE: no "skills"/"agents" fields — Copilot defaults to skills/ and agents/
    (out / "plugin.json").write_text(json.dumps(manifest, indent=2) + "\n")

    for d in skill_dirs:
        fm, body = parse_frontmatter((d / "SKILL.md").read_text(), d / "SKILL.md")
        body = substitute(strip_path_note(body), PLUGIN_REFS)
        # re-insert the plugin-flavored path note under the title line
        body = re.sub(r"^(# .*\n)", r"\1\n" + PLUGIN_NOTE, body, count=1, flags=re.M)
        dest = out / "skills" / fm["name"] / "SKILL.md"
        dest.parent.mkdir(parents=True)
        dest.write_text(f"{skill_frontmatter(fm)}<!-- {MARKER} -->\n{body}")
        copy_skill_support(d, dest.parent, PLUGIN_REFS)

    (out / "agents").mkdir()
    for f in agent_files:
        fm, body = parse_frontmatter(f.read_text(), f)
        body = substitute(strip_path_note(body), PLUGIN_REFS)
        (out / "agents" / f"{fm['name']}.agent.md").write_text(
            f"{agent_frontmatter(fm)}"
            f"<!-- {MARKER} -->\n{PLUGIN_NOTE}> You are read-only: report findings in your"
            f" defined format; never modify\n> files or repository state.\n\n{body}")

    for dirname in ("templates", "checklists", "core", "standards", "knowledge"):
        shutil.copytree(stack / dirname, out / dirname, ignore=IGNORE)
    restore_knowledge(out, stashed)
    (out / "scripts").mkdir()
    for sh in runtime_scripts(stack):
        shutil.copy2(sh, out / "scripts" / sh.name)

    m = re.search(r"github\.com[/:]([^/]+/[^/.]+)", src_manifest.get("repository", ""))
    repo_spec = f"{m.group(1) if m else 'OWNER/REPO'}:copilot"
    (out / "README.md").write_text(f"""<!-- {MARKER} -->
# software-engineer-stack — Copilot plugin

Ready-to-use GitHub Copilot plugin: the full lifecycle framework (skills,
reviewer agents, templates, checklists, decision protocol, standards) in
Copilot's native plugin layout. No generator run needed.

## Install

```sh
copilot plugin install ./copilot          # from a local checkout
copilot plugin install {repo_spec}   # or straight from GitHub
```

Install this folder, never the repository root: the root's
`.claude-plugin/plugin.json` is the Claude Code flavor, whose skills keep
unresolved `${{CLAUDE_PLUGIN_ROOT}}` paths and whose reviewers are not
`.agent.md` custom agents.

Verify: `copilot plugins list`, then `/skills list` and `/agent` in a session.
Components are cached — after updating the checkout, run the install command
again to pick up changes. The install replaces the cached copy wholesale, so
lessons /retro appended to the installed `knowledge/` are lost on update:
upstream them to the framework repo's `knowledge/lessons.md` first. For the
Copilot cloud agent, enable the plugin via `enabledPlugins` in the work repo's
`.github/copilot/settings.json`.

## Contents

- `skills/` — the {len(skill_dirs)} lifecycle stages (model-invoked; describe what you want,
  e.g. "start a new task from this brief", and the matching stage loads)
- `agents/` — scope-auditor, code-reviewer, doc-fact-checker as custom agents
- `templates/ checklists/ core/ standards/ scripts/` — the data the skills use
- `knowledge/` — lessons + decisions memory (a per-install copy: /retro writes
  lessons here, and rebuilds merge them back on top of the canonical content
  rather than replacing it, so entries survive regeneration; still sync
  anything broadly useful back to the framework repo's `knowledge/`)

## Maintenance

This folder is GENERATED from the canonical `skills/` and `agents/` at the
repository root — edit those and run `python3 scripts/build_copilot.py`;
never edit files here directly.
""")
    print(f"wrote plugin folder {out} ({len(skill_dirs)} skills, {len(agent_files)} agents)")


def build_bundle(stack: Path, target: Path) -> None:
    """Copy the framework data into <target>/.github/se-stack/ (self-contained mode)."""
    out = target / ".github" / "se-stack"
    gen_marker = out / ".generated"
    if out.exists() and not gen_marker.exists():
        sys.exit(f"error: {out} exists and was not generated by this script — refusing to overwrite")
    stashed = stash_knowledge(out)
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    gen_marker.write_text(MARKER + "\n")
    for dirname in ("templates", "checklists", "core", "standards", "knowledge"):
        shutil.copytree(stack / dirname, out / dirname, ignore=IGNORE)
    restore_knowledge(out, stashed)
    (out / "scripts").mkdir()
    for sh in runtime_scripts(stack):
        shutil.copy2(sh, out / "scripts" / sh.name)
    (out / "README.md").write_text(f"""<!-- {MARKER} -->
# se-stack — bundled framework data (self-contained mode)

Copied from the software-engineer-stack repo by scripts/build_copilot.py
--self-contained so this work repo needs no framework checkout. The skills
and agents under .github/ reference these copies.

- Do not edit here — edit the framework repo and regenerate.
- knowledge/ is the exception: it is a per-install copy that /retro appends to,
  and regeneration merges those entries back on top of the canonical content
  instead of overwriting them, so lessons and decisions recorded in this repo
  survive rebuilds. Sync anything broadly useful back to the framework repo's
  canonical knowledge/ so other installs get it too.
""")
    print(f"wrote bundle {out}")


def build_instructions(refs: Refs, skill_names: list[str]) -> str:
    root_ref = refs.root
    cmds = ", ".join(f"`/{n}`" for n in skill_names)
    return f"""<!-- {MARKER} -->
# software-engineer-stack — Copilot instructions

This repository is worked on with the software-engineer-stack lifecycle
framework rooted at `{root_ref}`. Each stage ({cmds}) is an agent skill
in `.github/skills/`, loaded automatically when a request matches its
description (VS Code, Copilot CLI, the Copilot app, the cloud agent) and
invocable by name as a slash command in VS Code chat.

Rules that apply to ALL work here:

1. **Decision protocol** (`{root_ref}/core/decision-protocol.md`): checkable
   facts are checked, never estimated. Proceed without asking only on
   ~90%+-confident, cheaply-reversible, in-scope calls with no dangerous
   surface — logged to the task workspace `ASSUMPTIONS.md`. Everything else
   (genuinely unknown, irreversible, data/prod-touching, scope-affecting)
   stops and asks. Open assumptions are ratified at every approval gate.
2. **Scope discipline**: the task's `work/<id>/scope-contract.md` is the
   single source of scope truth. Out-of-scope findings go to `PARKED.md`,
   never into the change.
3. **Repo rules**: follow the repo's own rules files (AGENTS.md, CLAUDE.md,
   CODING_STANDARDS.md, CONTRIBUTING.md, …) exactly as
   `{root_ref}/scripts/repo-rules.sh <repo> [files]` lists them — they
   override the framework defaults in `{root_ref}/standards/`; a nested
   AGENTS.md nearest the edited file wins. `<work-repo>` is the repo root
   resolved per `{root_ref}/core/repo-resolution.md` and recorded in the task
   `STATUS.md` — with a multi-repo workspace it is NOT your current
   directory, and task workspaces live in the folder holding the repos.
4. **Verification**: code claims require evidence — run it (see the
   verify-code skill) and capture output to the workspace `evidence/`
   directory. Fallback static checks must be labelled as such.
5. **Resumability**: the task workspace `STATUS.md` records stage state.
   Read and write it only through `{root_ref}/scripts/status.py`: gate with
   `status.py require <ws> <stage>=<state>` (non-zero exit = stop) before
   starting a stage, and record every transition with `status.py set`.
6. The review procedures (scope-auditor, code-reviewer, doc-fact-checker)
   are installed as Copilot custom agents in `.github/agents/` — where a
   skill says to run one, delegate to the matching custom agent (VS Code,
   Copilot CLI `/agent`, or the cloud agent). On a surface without
   custom-agent support, execute the procedure from `{refs.agents}/`
   yourself as a separate, fresh review pass held to its report format.
"""


def build_agents_md(skill_dirs: list[Path]) -> str:
    rows = []
    for d in skill_dirs:
        fm, _ = parse_frontmatter((d / "SKILL.md").read_text(), d / "SKILL.md")
        desc = fm["description"].split(". ")[0].rstrip(".")
        rows.append(f"| `/{fm['name']}` | {desc}. | `skills/{d.name}/SKILL.md` |")
    table = "\n".join(rows)
    return f"""<!-- {MARKER} -->
# software-engineer-stack

An end-to-end software engineering lifecycle framework for PL/SQL, SQL, KSH,
and Python codebases: brief → research → technical design → implementation
plan → verified code → audited delivery, plus fast paths for change requests
and documentation. Full docs: README.md.

## How any agent should use this repo

1. Read `core/decision-protocol.md` first — it governs every unknown
   (check facts; proceed-and-log only narrow, reversible calls; otherwise ask)
   — and `core/repo-resolution.md`, which fixes where files are read and
   written (`<work-repo>` = the repo holding `.git`, whose own rules files
   `scripts/repo-rules.sh` lists; `<workspace-root>` = the directory holding
   `work/` — the folder holding the repos in a multi-repo workspace; both
   recorded in `STATUS.md`, neither assumed to be the current directory).
2. Each lifecycle stage is a self-contained instruction file. Execute the one
   matching the task:

| Command | Purpose | Instructions |
|---|---|---|
{table}

3. Instruction files reference framework paths as `${{CLAUDE_PLUGIN_ROOT}}` —
   that is this repository's root. Claude Code resolves it natively; other
   harnesses substitute the repo path (the Copilot skill copies under
   `.github/skills/` and the `copilot/` plugin are pre-substituted;
   regenerate with `python3 scripts/build_copilot.py`).
4. Task state lives in `work/<task-id>/` workspaces (`STATUS.md` = resume
   point, `scope-contract.md` = scope truth, `ASSUMPTIONS.md` = logged
   judgment calls, `evidence/` = verification outputs). Stage gates are
   checked and recorded with `scripts/status.py` (`require` exits non-zero
   when a gate is not met), never by reading or editing STATUS.md by eye.
5. Review procedures in `agents/` (scope-auditor, code-reviewer,
   doc-fact-checker) run as subagents where supported — Claude Code agents
   natively, Copilot custom agents via the generated `.github/agents/` — and
   as separate fresh passes held to their report formats everywhere else.
6. Framework changes: edit the canonical files (`skills/`, `agents/`,
   `templates/`, `checklists/`, `core/`, `standards/`, `scripts/`), then run
   `python3 scripts/build_copilot.py` and commit the regenerated output. CI
   and `.githooks/pre-commit` run `build_copilot.py --check`,
   `scripts/check_knowledge.py`, and the tests in `tests/`.
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--target", type=Path, default=None,
                    help="work repo to install the Copilot adapter into (default: the stack repo)")
    ap.add_argument("--stack-root", type=Path, default=Path(__file__).resolve().parent.parent,
                    help="location of the software-engineer-stack repo")
    ap.add_argument("--self-contained", action="store_true",
                    help="bundle framework data into <target>/.github/se-stack/ and point "
                         "references there, so the work repo needs no framework checkout")
    ap.add_argument("--check", action="store_true",
                    help="verify the committed generated output is up to date; changes nothing")
    args = ap.parse_args()

    stack = args.stack_root.resolve()
    if args.check:
        if args.target or args.self_contained:
            sys.exit("error: --check verifies the stack repo's own output; drop --target/--self-contained")
        sys.exit(check(stack))
    target = (args.target or stack).resolve()
    if not (stack / "skills").is_dir():
        sys.exit(f"error: {stack} does not look like the stack repo (no skills/)")
    # inside the stack repo, references are repo-relative; elsewhere, absolute —
    # or bundle-relative in self-contained mode
    if target == stack:
        refs = Refs.at(".")
    elif args.self_contained:
        refs = BUNDLE_REFS
    else:
        refs = Refs.at(str(stack))

    gh = target / ".github"
    skill_dirs = sorted(d for d in (stack / "skills").iterdir() if (d / "SKILL.md").is_file())
    agent_files = sorted((stack / "agents").glob("*.md"))
    skills = [(d, *parse_frontmatter((d / "SKILL.md").read_text(), d / "SKILL.md")) for d in skill_dirs]
    agents = [parse_frontmatter(f.read_text(), f) for f in agent_files]
    names = [fm["name"] for _, fm, _ in skills]
    agent_names = [fm["name"] for fm, _ in agents]

    # refuse before writing anything, so a hand-written file never leaves a half-built install
    outputs = ([gh / "skills" / n / "SKILL.md" for n in names]
               + [gh / "agents" / f"{n}.agent.md" for n in agent_names]
               + [gh / "copilot-instructions.md", stack / "AGENTS.md"])
    handmade = [p for p in outputs if p.exists() and MARKER not in p.read_text()]
    trees = [stack / "copilot"] + ([gh / "se-stack"] if refs is BUNDLE_REFS else [])
    handmade += [d for d in trees if d.exists() and not (d / ".generated").exists()]
    if handmade:
        sys.exit("error: not generated by this script — refusing to overwrite:\n  "
                 + "\n  ".join(map(str, handmade)))
    if refs is BUNDLE_REFS:
        build_bundle(stack, target)

    for d, fm, body in skills:
        # a generated skill dir is rebuilt whole, so support files dropped upstream go too
        if (gh / "skills" / fm["name"] / "SKILL.md").exists():
            shutil.rmtree(gh / "skills" / fm["name"])
        write_generated(gh / "skills" / fm["name"] / "SKILL.md", build_skill(fm, body, refs))
        copy_skill_support(d, gh / "skills" / fm["name"], refs)
    for fm, body in agents:
        write_generated(gh / "agents" / f"{fm['name']}.agent.md", build_agent(fm, body, refs))
    prune_generated(gh, names, agent_names)

    write_generated(gh / "copilot-instructions.md", build_instructions(refs, names))
    write_generated(stack / "AGENTS.md", build_agents_md(skill_dirs))
    build_plugin(stack, skill_dirs, agent_files)
    print(f"done: {len(names)} skills + "
          f"{len(agent_files)} custom agents → {target / '.github'}")


def _tree_files(base: Path) -> set[str]:
    out = set()
    for rel in GENERATED_PATHS:
        p = base / rel
        if p.is_file():
            out.add(rel)
        elif p.is_dir():
            out |= {str(f.relative_to(base)) for f in p.rglob("*")
                    if f.is_file() and "__pycache__" not in f.parts and f.suffix != ".pyc"}
    return out


def check(stack: Path) -> int:
    """Rebuild into a scratch copy of the repo and diff the generated paths."""
    with tempfile.TemporaryDirectory(prefix="se-stack-check-") as tmp:
        scratch = Path(tmp) / "stack"
        shutil.copytree(stack, scratch, ignore=shutil.ignore_patterns(
            ".git", "work", "__pycache__", "*.pyc", "node_modules", ".venv"))
        # rebuild from nothing: leftovers in the copy would otherwise mask orphaned files
        for rel in GENERATED_PATHS:
            p = scratch / rel
            if p.is_dir():
                shutil.rmtree(p)
            elif p.exists():
                p.unlink()
        r = subprocess.run([sys.executable, str(scratch / "scripts" / "build_copilot.py"),
                            "--stack-root", str(scratch)], capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stdout + r.stderr, file=sys.stderr)
            print("error: build failed in scratch copy", file=sys.stderr)
            return 2
        have, want = _tree_files(stack), _tree_files(scratch)
        stale = sorted(f for f in have & want if not filecmp.cmp(stack / f, scratch / f, shallow=False))
        missing = sorted(want - have)
        extra = sorted(have - want)
    for label, files in (("out of date", stale), ("missing", missing), ("no longer generated", extra)):
        for f in files:
            print(f"{label}: {f}", file=sys.stderr)
    if stale or missing or extra:
        print("generated output is stale — run: python3 scripts/build_copilot.py "
              "(then commit the result)", file=sys.stderr)
        return 1
    print("generated output up to date")
    return 0


