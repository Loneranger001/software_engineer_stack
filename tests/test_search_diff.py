"""Tests for scripts/xsearch.py and scripts/review-diff.sh."""
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
MARKER = "<!-- generated by software-engineer-stack scripts/build_copilot.py; do not edit by hand -->\n"


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True)


def make_repo(path, files):
    subprocess.run(["git", "init", "-q", "-b", "main", str(path)], check=True)
    git(path, "config", "user.email", "t@example.com")
    git(path, "config", "user.name", "t")
    for rel, text in files.items():
        f = path / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
    git(path, "add", "-A")
    git(path, "commit", "-qm", "init")


class XsearchTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        b = Path(self.tmp.name)
        make_repo(b / "repo-a", {"src/a.pkb": "pkg_balance.snapshot;\npkg_balance.extract;\n",
                                 "src/b.pkb": "PKG_BALANCE.x;\n"})
        make_repo(b / "repo-b", {"bin/run.ksh": "sqlplus @pkg_balance\n"})
        make_repo(b / "repo-c", {"README": "unrelated\n"})
        self.repos = ",".join(str(b / r) for r in ("repo-a", "repo-b", "repo-c"))
        self.base = b

    def tearDown(self):
        self.tmp.cleanup()

    def xs(self, *args):
        return subprocess.run([sys.executable, str(SCRIPTS / "xsearch.py"), *map(str, args)],
                              capture_output=True, text=True)

    def test_every_repo_reported_including_zero_hits(self):
        r = self.xs("--repos", self.repos, "-i", "--", "pkg_balance")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("## repo-a (worktree@", r.stdout)
        self.assertIn("3 match(es) in 2 file(s)", r.stdout)
        self.assertIn("## repo-c (worktree@", r.stdout)
        self.assertIn("searched, no references found", r.stdout)
        self.assertEqual(r.stdout.count("| repo-"), 3)

    def test_case_sensitive_by_default(self):
        r = self.xs("--repos", self.repos, "--", "pkg_balance")
        self.assertIn("2 match(es) in 1 file(s)", r.stdout)

    def test_top_caps_listing_and_save_keeps_everything(self):
        out = self.base / "ev" / "search.txt"
        r = self.xs("--repos", self.repos, "-i", "--top", "1", "--save", out, "--", "pkg_balance")
        self.assertIn("1 more file(s)", r.stdout)
        saved = out.read_text()
        self.assertIn("src/a.pkb", saved)
        self.assertIn("src/b.pkb", saved)

    def test_ref_search_and_missing_ref_is_not_skipped(self):
        git(self.base / "repo-a", "update-ref", "refs/remotes/origin/main", "HEAD")
        r = self.xs("--repos", self.repos, "--ref", "origin/main", "-i", "--", "pkg_balance")
        self.assertEqual(r.returncode, 1)
        self.assertIn("## repo-a (origin/main@", r.stdout)
        self.assertIn("repo-b: NOT SEARCHED", r.stdout)

    def test_workspace_repo_set(self):
        subprocess.run(["sh", str(SCRIPTS / "new-task.sh"), "X-1", "auto", "full",
                        str(self.base / "repo-a"), self.repos], check=True, capture_output=True)
        r = self.xs("--ws", self.base / "work" / "X-1", "-F", "--", "@pkg_balance")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("repos: 3", r.stdout)
        self.assertIn("1 match(es) in 1 file(s)", r.stdout)


class ReviewDiffTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name) / "repo"
        make_repo(self.repo, {"src/a.pkb": "v1\n"})
        git(self.repo, "checkout", "-qb", "feat")
        for rel, text in {"src/a.pkb": "v1\nv2\n", "src/sql/x.sql": "alter;\n",
                          "work/T-1/STATUS.md": "s\n", ".github/copilot-instructions.md": MARKER,
                          "package-lock.json": "{}\n"}.items():
            f = self.repo / rel
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(text)
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-qm", "change")

    def tearDown(self):
        self.tmp.cleanup()

    def rd(self, *args):
        return subprocess.run(["sh", str(SCRIPTS / "review-diff.sh"), str(self.repo), *args],
                              capture_output=True, text=True)

    def test_plan_splits_review_and_skip(self):
        out = self.rd("main", "feat").stdout
        review, _, skip = out.partition("skip:")
        self.assertIn("src/a.pkb", review)
        self.assertIn("src/sql/x.sql", review)
        self.assertIn("work/T-1/STATUS.md  (task workspace)", skip)
        self.assertIn(".github/copilot-instructions.md  (framework-generated)", skip)
        self.assertIn("package-lock.json  (lockfile/minified)", skip)
        self.assertNotIn("+v2", out)  # the plan never prints diff content

    def test_file_mode_shows_one_file(self):
        out = self.rd("main", "feat", "--file", "src/a.pkb").stdout
        self.assertIn("+v2", out)
        self.assertNotIn("x.sql", out)

    def test_bad_ref_is_an_error(self):
        self.assertEqual(self.rd("nope", "feat").returncode, 2)


if __name__ == "__main__":
    unittest.main()
