"""Tests for scripts/workspace-root.sh, scripts/repo-rules.sh and new-task.sh's auto root."""
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
MARKER = "<!-- generated by software-engineer-stack scripts/build_copilot.py; do not edit by hand -->\n"


def sh(script, *args, cwd=None, env=None):
    e = {k: v for k, v in os.environ.items() if k != "SES_WORKSPACE_ROOT"}
    e.update(env or {})
    return subprocess.run(["sh", str(SCRIPTS / script), *map(str, args)], cwd=cwd, env=e,
                          capture_output=True, text=True)


def git_init(path):
    path.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", str(path)], check=True)


class WorkspaceRootTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.base = Path(self.tmp.name)
        self.ws = self.base / "My Workspace"          # space on purpose
        for r in ("repo-a", "repo-b"):
            git_init(self.ws / r)
        (self.ws / "repo-a" / "src").mkdir()

    def tearDown(self):
        self.tmp.cleanup()

    def test_multi_repo_parent_from_inside_a_repo(self):
        r = sh("workspace-root.sh", self.ws / "repo-a" / "src")
        self.assertEqual(r.stdout.strip(), str(self.ws), r.stderr)

    def test_parent_folder_itself(self):
        self.assertEqual(sh("workspace-root.sh", self.ws).stdout.strip(), str(self.ws))

    def test_standalone_repo_keeps_work_inside(self):
        solo = self.base / "solo"
        git_init(solo)
        self.assertEqual(sh("workspace-root.sh", solo).stdout.strip(), str(solo))

    def test_env_override_wins(self):
        r = sh("workspace-root.sh", self.ws / "repo-a", env={"SES_WORKSPACE_ROOT": str(self.base)})
        self.assertEqual(r.stdout.strip(), str(self.base))

    def test_no_repo_anywhere_is_an_error(self):
        empty = self.base / "empty"
        empty.mkdir()
        self.assertEqual(sh("workspace-root.sh", empty).returncode, 1)

    def test_new_task_auto_puts_work_in_parent(self):
        r = sh("new-task.sh", "T-1", "auto", "full", self.ws / "repo-a")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue((self.ws / "work" / "T-1" / "STATUS.md").is_file())
        self.assertFalse((self.ws / "repo-a" / "work").exists())

    def test_new_task_default_from_cwd_inside_repo(self):
        r = sh("new-task.sh", "T-2", cwd=self.ws / "repo-a" / "src")
        self.assertEqual(r.returncode, 0, r.stderr)
        status = (self.ws / "work" / "T-2" / "STATUS.md").read_text()
        self.assertIn(f"- work-repo: {self.ws / 'repo-a'}", status)
        self.assertIn(f"- workspace-root: {self.ws}", status)

    def test_new_task_reports_root_source(self):
        r = sh("new-task.sh", "T-3", "auto", "full", self.ws / "repo-a")
        self.assertIn(f"workspace root: {self.ws} (auto, from ses workspace-root)", r.stdout)
        pinned = self.base / "pinned"
        pinned.mkdir()
        r = sh("new-task.sh", "T-4", "auto", "full", self.ws / "repo-a", env={"SES_WORKSPACE_ROOT": str(pinned)})
        self.assertIn(f"workspace root: {pinned} (pinned by SES_WORKSPACE_ROOT)", r.stdout)


class ExistingWorkspaceTest(unittest.TestCase):
    """An existing task id resumes silently only when it is plainly the same task."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.ws = Path(self.tmp.name) / "apps"
        for r in ("repo-a", "repo-b"):
            git_init(self.ws / r)
        r = sh("new-task.sh", "CHG-1", "auto", "full", self.ws / "repo-a")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.status = self.ws / "work" / "CHG-1" / "STATUS.md"
        self.before = self.status.read_text()

    def tearDown(self):
        self.tmp.cleanup()

    def test_same_repo_and_pipeline_resumes(self):
        r = sh("new-task.sh", "CHG-1", "auto", "full", self.ws / "repo-a")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("workspace already exists", r.stderr)

    def test_other_work_repo_asks(self):
        r = sh("new-task.sh", "CHG-1", "auto", "full", self.ws / "repo-b")
        self.assertEqual(r.returncode, 3)
        self.assertIn("ASK THE USER", r.stderr)
        self.assertIn(f"work-repo {self.ws / 'repo-a'}", r.stderr)
        self.assertIn(f"work-repo {self.ws / 'repo-b'}", r.stderr)
        self.assertEqual(self.status.read_text(), self.before)

    def test_other_pipeline_asks(self):
        r = sh("new-task.sh", "CHG-1", "auto", "change-request", self.ws / "repo-a")
        self.assertEqual(r.returncode, 3)
        self.assertIn("pipeline full", r.stderr)
        self.assertEqual(self.status.read_text(), self.before)

    def test_same_id_under_old_root_asks_instead_of_duplicating(self):
        pinned = Path(self.tmp.name) / "pinned"
        pinned.mkdir()
        r = sh("new-task.sh", "CHG-1", "auto", "full", self.ws / "repo-a", env={"SES_WORKSPACE_ROOT": str(pinned)})
        self.assertEqual(r.returncode, 3)
        self.assertIn(str(self.ws / "work" / "CHG-1"), r.stderr)
        self.assertFalse((pinned / "work").exists())

    def test_legacy_workspace_inside_repo_asks(self):
        legacy = self.ws / "repo-b" / "work" / "OLD-1"
        legacy.mkdir(parents=True)
        (legacy / "STATUS.md").write_text("# STATUS — OLD-1\n")
        r = sh("new-task.sh", "OLD-1", "auto", "full", self.ws / "repo-b")
        self.assertEqual(r.returncode, 3)
        self.assertFalse((self.ws / "work" / "OLD-1").exists())


class RepoRulesTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name) / "repo with space"
        git_init(self.repo)
        (self.repo / "AGENTS.md").write_text("root rules\n")
        (self.repo / "docs").mkdir()
        (self.repo / "docs" / "Coding_Standards.md").write_text("standards\n")
        (self.repo / ".github" / "instructions").mkdir(parents=True)
        (self.repo / ".github" / "copilot-instructions.md").write_text(MARKER)
        (self.repo / ".github" / "instructions" / "sql.instructions.md").write_text("sql\n")
        pkg = self.repo / "src" / "plsql" / "billing"
        pkg.mkdir(parents=True)
        (self.repo / "src" / "plsql" / "AGENTS.md").write_text("plsql rules\n")
        (pkg / "pkg.pkb").write_text("x\n")
        (self.repo / "pyproject.toml").write_text("")

    def tearDown(self):
        self.tmp.cleanup()

    def lines(self, *args):
        r = sh("repo-rules.sh", self.repo, *args)
        self.assertEqual(r.returncode, 0, r.stderr)
        return r.stdout.splitlines()

    def test_lists_rules_case_insensitively_and_skips_generated(self):
        out = self.lines()
        self.assertIn("rules:   AGENTS.md", out)
        self.assertIn("rules:   docs/Coding_Standards.md", out)
        self.assertIn("rules:   .github/instructions/sql.instructions.md", out)
        self.assertNotIn("rules:   .github/copilot-instructions.md", out)
        self.assertIn("tooling: pyproject.toml", out)

    def test_nested_agents_md_for_changed_file_comes_last(self):
        out = [l for l in self.lines("src/plsql/billing/pkg.pkb") if l.startswith("rules:")]
        self.assertEqual(out[-1], "rules:   src/plsql/AGENTS.md")
        self.assertEqual(out.count("rules:   AGENTS.md"), 1)

    def test_none_found_is_explicit(self):
        bare = Path(self.tmp.name) / "bare"
        git_init(bare)
        r = sh("repo-rules.sh", bare)
        self.assertIn("rules:   (none found", r.stdout)

    def test_not_a_repo_is_an_error(self):
        plain = Path(self.tmp.name) / "plain"
        plain.mkdir()
        self.assertEqual(sh("repo-rules.sh", plain).returncode, 2)


if __name__ == "__main__":
    unittest.main()
